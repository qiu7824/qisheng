fn bitnum(a: &[u8], b: usize, c: u32) -> u32 {
    ((a[b / 32 * 4 + 3 - (b % 32) / 8] as u32 >> (7 - b % 8)) & 1) << c
}
fn intr(a: u32, b: u32, c: u32) -> u32 {
    ((a >> (31 - b)) & 1) << c
}
fn intl(a: u32, b: u32, c: u32) -> u32 {
    (a.wrapping_shl(b) & 0x80000000) >> c
}
fn sbit(a: u8) -> usize {
    ((a & 32) | ((a & 31) >> 1) | ((a & 1) << 4)) as usize
}
